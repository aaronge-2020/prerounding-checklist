import assert from 'node:assert/strict';
import { moveNoteText, appendSourceSelection } from '../src/patient-context/note-mapping.js';
const fieldIds = ['hpi','exam','plan','other'];
const original = { hpi:'Cough.\nLungs clear.\n', exam:'Alert.', plan:'Review results.' };
const start=original.hpi.indexOf('Lungs');
const moved=moveNoteText(original,{from:'hpi',to:'exam',start,end:start+12,fieldIds});
assert.equal(moved.hpi,'Cough.\n\n');
assert.equal(moved.exam,'Alert.\n\nLungs clear.');
assert.equal(moved.plan,original.plan);
assert.equal(original.hpi,'Cough.\nLungs clear.\n');
assert.throws(()=>moveNoteText(original,{from:'hpi',to:'hpi',fieldIds}));
assert.throws(()=>moveNoteText(original,{from:'hpi',to:'exam',start:9,end:500,fieldIds}));
assert.throws(()=>moveNoteText(original,{from:'hpi',to:'exam',start:0,end:0,fieldIds}));
const whole=moveNoteText(original,{from:'hpi',to:'other',fieldIds});
assert.equal(whole.other,original.hpi);assert.equal(whole.hpi,'');
const restore=appendSourceSelection(original,{text:'Missed passage',start:0,end:6,to:'plan',fieldIds});
assert.equal(restore.plan,'Review results.\n\nMissed');
assert.throws(()=>appendSourceSelection(original,{text:'abc',start:0,end:4,to:'plan',fieldIds}));
console.log('Note mapping: exact ranges, destination preservation, invalid ranges and source restoration passed.');
