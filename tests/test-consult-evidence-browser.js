import assert from "node:assert/strict";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright";
import { createAppServer, openRealApp, unlockAndCreatePatient } from "./browser/app-harness.js";
import { installSyntheticDeid, approveFinalRequest } from "./browser/external-ai-fixture.js";
const server = await createAppServer();
const browser = await chromium.launch({ ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}), args: ["--no-proxy-server"] });
try {
  const page = await browser.newPage({ serviceWorkers: "block", viewport: { width: 1280, height: 900 } });
  await installSyntheticDeid(page);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const requests = [];
  let missingEvidence = false;
  const url = "https://example.org/synthetic-clinical-study";
  const summary = "Synthetic study included people with kidney impairment. Applicability and uncertainty require clinician review.";
  await page.route("https://api.openai.com/v1/responses", async route => {
    const body = route.request().postDataJSON();
    requests.push(body);
    let payload;
    if (body.text?.format.name === "consult_evidence_question") payload = { output_text: JSON.stringify({ question: "Find primary evidence for heart failure treatment with eGFR 25, including applicability and limitations." }) };
    else if (body.tools?.[0]?.type === "web_search") payload = {
      output_text: missingEvidence ? "No useful cited evidence found." : summary,
      output: [{ type: "web_search_call", status: "completed", action: { sources: missingEvidence ? [] : [{ url, title: "Synthetic clinical study" }] } }]
    };
    else payload = { output_text: JSON.stringify({ suggestions: [{ id: 1, target: "diagnostic_plan", action: "add", anchor: "", suggested: "Discuss evidence applicability with supervising clinician.", rationale: "The documented eGFR is relevant to the retrieved population; benefit remains uncertain.", likelihood: "", citationIds: [1] }], references: [{ id: 1, title: "Synthetic clinical study", authors: "", journal: "", year: "", url, excerpt: "Synthetic study included people with kidney impairment.", sourceLocation: "Retrieved evidence summary" }] }) };
    await route.fulfill({ contentType: "application/json", body: JSON.stringify({ status: "completed", ...payload }) });
  });
  await openRealApp(page, server.baseUrl);
  await unlockAndCreatePatient(page);
  await page.click('[data-action="select-structured-note-mode"][data-note-scope="admission"][data-note-mode="sections"]');
  await page.fill('[data-structured-note-scope="admission"][data-structured-note-field="one_liner"]', "Adult with heart failure.");
  await page.click('[data-action="save-structured-primary-note"][data-note-scope="admission"]');
  await page.waitForFunction(() => /saved/i.test(document.querySelector("#statusLine")?.textContent || ""));
  await page.click('[data-action="open-admission-note"]');
  await page.click('[data-action="add-plan-problem"]');
  const card = page.locator(".plan-problem-card").last();
  const problemId = await card.getAttribute("data-problem-id");
  await card.locator('[data-problem-field="problem"]').fill("Heart failure");
  await card.locator('[data-problem-field="keyContext"]').fill("CHART_CONTEXT_MARKER: eGFR 25; prior treatment ineffective.");
  const openConsult = async () => {
    await page.locator(`[data-problem-id="${problemId}"] [data-action="generate-ap"]`).click();
    assert.equal(await page.locator('[data-ap-request-field="evidenceBased"]').isChecked(), true);
    await page.screenshot({ path: join(tmpdir(), "preround-consult-evidence-setup.png") });
    await page.locator("[data-ap-request-key]").fill("synthetic-key");
    await page.locator('[data-action="ap-confirm-generate"]').click();
    await page.locator("[data-external-ai-review]").waitFor();
  };
  await openConsult();
  assert.equal(requests.length, 0);
  await approveFinalRequest(page);
  await page.waitForFunction(() => document.querySelector("[data-external-search-reviewed]"));
  assert.equal(requests.length, 1);
  assert.equal(requests[0].tools, undefined);
  const question = page.locator('[data-external-field="input"]');
  assert.doesNotMatch(await question.inputValue(), /CHART_CONTEXT_MARKER/);
  const edited = "Edited evidence question: heart failure treatment in kidney impairment with eGFR 25?";
  await question.fill(edited);
  await page.screenshot({ path: join(tmpdir(), "preround-consult-evidence-question.png") });
  await approveFinalRequest(page);
  await page.waitForFunction(() => document.querySelector('[data-external-field="instructions"]') && !document.querySelector("[data-external-search-reviewed]"));
  assert.equal(requests.length, 2);
  assert.equal(requests[1].input, edited);
  assert.equal(requests[1].instructions, undefined);
  assert.equal(requests[1].tool_choice, "required");
  assert.doesNotMatch(JSON.stringify(requests[1]), /CHART_CONTEXT_MARKER/);
  const synthesis = await page.locator('[data-external-field="input"]').inputValue();
  assert.match(synthesis, /CHART_CONTEXT_MARKER/);
  assert.ok(synthesis.includes(edited));
  assert.ok(synthesis.includes(summary));
  assert.ok(synthesis.includes("Source 1"));
  assert.ok(!synthesis.includes(url), "source URLs are bound locally rather than generated from redacted prompt text");
  await approveFinalRequest(page);
  await page.locator(".ap-inline-change").waitFor();
  assert.equal(requests.length, 3);
  assert.equal(requests[2].tools, undefined);
  for (const request of requests) assert.equal(request.store, false);
  await page.locator('[data-action="ap-suggestion-approve"]').first().click();
  assert.match(await page.locator(`[data-problem-id="${problemId}"] [data-problem-field="diagnosticPlan"]`).innerText(), /Discuss evidence applicability/);
  const retainedPlan = await page.locator(`[data-problem-id="${problemId}"] [data-problem-field="diagnosticPlan"]`).innerText();
  await openConsult();
  await approveFinalRequest(page);
  await page.locator("[data-external-search-reviewed]").waitFor();
  await page.locator("[data-external-cancel]").click();
  await page.waitForFunction(() => !document.querySelector("[data-ap-loading]"));
  assert.equal(requests.length, 4, "cancelling the search question cannot search or synthesize");
  missingEvidence = true;
  await openConsult();
  await approveFinalRequest(page);
  await page.locator("[data-external-search-reviewed]").waitFor();
  await approveFinalRequest(page);
  await page.waitForFunction(() => !document.querySelector("[data-ap-loading]"));
  assert.equal(requests.length, 6, "missing sources cannot trigger final synthesis");
  assert.match(await page.locator("#statusLine").textContent(), /No cited web evidence/);
  assert.equal(await page.locator(`[data-problem-id="${problemId}"] [data-problem-field="diagnosticPlan"]`).innerText(), retainedPlan);
  missingEvidence = false;
  await openConsult();
  await approveFinalRequest(page);
  await page.locator("[data-external-search-reviewed]").waitFor();
  await page.evaluate(() => document.querySelector('[data-action="lock-vault"]').click());
  await page.waitForFunction(() => !document.querySelector("[data-external-ai-review]"));
  assert.equal(requests.length, 7);
  assert.equal(await page.locator("#reviewContent").innerHTML(), "");
  assert.deepEqual(errors, []);
  console.log("PASS: patient-specific consult proposes, reviews and edits an isolated search question, retrieves sources, synthesizes with chart context, requires approval, and stops on cancellation, missing evidence and vault lock.");
} finally { await browser.close(); await server.close(); }
